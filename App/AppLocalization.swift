import SwiftUI
import SwitcherCore

enum AppLocalization {
    static let defaultLanguage = "zh"

    static func normalized(_ language: String) -> String {
        language == "en" ? "en" : defaultLanguage
    }

    static func locale(for language: String) -> Locale {
        Locale(identifier: normalized(language) == "en" ? "en_US" : "zh_Hans_CN")
    }

    static func text(_ key: String, language: String, arguments: [String: String] = [:]) -> String {
        let language = normalized(language)
        var result = values[language]?[key] ?? values[defaultLanguage]?[key] ?? key
        for (name, value) in arguments {
            result = result.replacingOccurrences(of: "{\(name)}", with: value)
        }
        return result
    }

    static func date(_ date: Date, language: String, dateStyle: DateFormatter.Style = .none,
                     timeStyle: DateFormatter.Style = .none, relative: Bool = false) -> String {
        let formatter = DateFormatter()
        formatter.locale = locale(for: language)
        formatter.dateStyle = dateStyle
        formatter.timeStyle = timeStyle
        formatter.doesRelativeDateFormatting = relative
        return formatter.string(from: date)
    }

    static func decision(_ decision: SafetyDecision, language: String) -> String {
        let arguments = [
            "observed": decision.observedCountry ?? text("common.unknown", language: language),
            "expected": decision.expectedCountry ?? text("common.unknown", language: language)
        ]
        return text("decision.\(decision.reason.rawValue)", language: language, arguments: arguments)
    }

    static func message(_ message: String, language: String) -> String {
        guard normalized(language) == "en" else { return message }
        if let translated = generatedMessages[message] { return translated }
        for (prefix, translation) in generatedPrefixes where message.hasPrefix(prefix) {
            return translation + String(message.dropFirst(prefix.count))
        }
        return message
    }

